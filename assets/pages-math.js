  function esc(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }
  function group(s, i) {
    if (s.charAt(i) !== "{") { return [s.charAt(i), i + 1]; }
    var depth = 0;
    for (var j = i; j < s.length; j++) {
      if (s.charAt(j) === "{") { depth++; } else if (s.charAt(j) === "}") { depth--; if (!depth) { return [s.slice(i + 1, j), j + 1]; } }
    }
    return [s.slice(i + 1), s.length];
  }
  function mx(s) {
    var out = "", i = 0, g, g2;
    while (i < s.length) {
      if (s.indexOf("\\frac", i) === i) {
        g = group(s, i + 5); g2 = group(s, g[1]);
        out += '<span class="mfrac"><span>' + mx(g[0]) + "</span><span>" + mx(g2[0]) + "</span></span>"; i = g2[1];
      } else if (s.indexOf("\\sqrt", i) === i) {
        g = group(s, i + 5); out += '√<span class="msqrt">' + mx(g[0]) + "</span>"; i = g[1];
      } else if (s.indexOf("\\lim", i) === i) {
        g = group(s, i + 4); out += '<span class="mop">lim<span>' + mx(g[0]) + "</span></span>"; i = g[1];
      } else if (s.indexOf("\\sum", i) === i) {
        g = group(s, i + 4); g2 = group(s, g[1]);
        out += '<span class="mop msum"><small>' + mx(g2[0]) + "</small>Σ<span>" + mx(g[0]) + "</span></span>"; i = g2[1];
      } else if (s.indexOf("\\log", i) === i) {
        out += '<span class="mfn">log</span>'; i += 4;
      } else if (s.indexOf("\\ln", i) === i) {
        out += '<span class="mfn">ln</span>'; i += 3;
      } else if (s.indexOf("\\text", i) === i) {
        g = group(s, i + 5); out += '<span class="mfn">' + esc(g[0]) + "</span>"; i = g[1];
      } else if (s.charAt(i) === "^" || s.charAt(i) === "_") {
        var tag = s.charAt(i) === "^" ? "sup" : "sub";
        g = group(s, i + 1); out += "<" + tag + ">" + mx(g[0]) + "</" + tag + ">"; i = g[1];
      } else { out += esc(s.charAt(i)); i++; }
    }
    return out;
  }
  function rich(s) {
    return String(s).split("$").map(function (part, i) {
      return i % 2 ? '<span class="mx">' + mx(part) + "</span>" : esc(part).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
    }).join("");
  }
  function richEl(tag, cls, s) { var n = el(tag, cls); n.innerHTML = rich(s); return n; }

